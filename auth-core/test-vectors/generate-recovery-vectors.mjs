// Generates recovery-v2.json: recovery protocol 2 (recoveryService.ts) with
// fixed inputs, so Auth Core, iOS and Android are checked against the same
// bytes. Run: node test-vectors/generate-recovery-vectors.mjs
import { createCipheriv, createECDH, createHash, createPrivateKey, createPublicKey, hkdfSync, pbkdf2Sync, sign } from 'node:crypto';
import { writeVectors } from './vector-files.mjs';

const sha256hex = (b) => createHash('sha256').update(b).digest('hex');

/** A P-256 key pair from a fixed scalar (test vectors only). */
function keyFromScalar(hex) {
  const ecdh = createECDH('prime256v1');
  ecdh.setPrivateKey(Buffer.from(hex, 'hex'));
  const publicKey = createPublicKey({ key: { kty: 'EC', crv: 'P-256', x: ecdh.getPublicKey().subarray(1, 33).toString('base64url'), y: ecdh.getPublicKey().subarray(33).toString('base64url') }, format: 'jwk' });
  const privateKey = createPrivateKey({ key: { kty: 'EC', crv: 'P-256', d: Buffer.from(hex, 'hex').toString('base64url'), x: ecdh.getPublicKey().subarray(1, 33).toString('base64url'), y: ecdh.getPublicKey().subarray(33).toString('base64url') }, format: 'jwk' });
  return { privateKey, publicKey, pem: publicKey.export({ type: 'spki', format: 'pem' }).toString(), spki: publicKey.export({ type: 'spki', format: 'der' }) };
}

// The BIP-39 test mnemonic (valid checksum).
const phrase = ['abandon', 'abandon', 'abandon', 'abandon', 'abandon', 'abandon', 'abandon', 'abandon', 'abandon', 'abandon', 'abandon', 'about'];
const salt = Buffer.from('000102030405060708090a0b0c0d0e0f', 'hex');
const iterations = 1000; // production uses 210000; the vectors keep tests fast
const nexusId = '123456789';
const credentialId = '00000000-0000-4000-8000-000000000002';

const seed = pbkdf2Sync(Buffer.from(phrase.join(' '), 'utf8'), salt, iterations, 32, 'sha256');
const wrapKey = Buffer.from(hkdfSync('sha256', seed, Buffer.from('NEXUS-SIGN/RECOVERY-WRAP/v2'), Buffer.from(nexusId), 32));

const recoveryScalar = 'c9afa9d845ba75166b5c215767b1d6934e50c3db36e89b127b8a622b120f6721';
const recovery = keyFromScalar(recoveryScalar);
const iv = Buffer.from('0102030405060708090a0b0c', 'hex');
const aad = Buffer.from(`NEXUS-SIGN/RECOVERY-KEY/v2\n${nexusId}\n${sha256hex(recovery.spki)}`, 'utf8');
const cipher = createCipheriv('aes-256-gcm', wrapKey, iv);
cipher.setAAD(aad);
const wrapped = Buffer.concat([iv, cipher.update(Buffer.from(recoveryScalar, 'hex')), cipher.final(), cipher.getAuthTag()]);

const setupInput = ['NEXUS-SIGN/RECOVERY-SETUP/v2', nexusId, credentialId, salt.toString('base64'), sha256hex(recovery.spki), sha256hex(wrapped)].join('\n');

const newSigning = keyFromScalar('0f2c7a1b5e8d3c6f9a2b4d7e0c1f3a5b8d9e2c4f6a7b1d3e5f8a0c2b4d6e8f1a');
const sessionId = '00000000-0000-4000-8000-0000000000aa';
const nonce = Buffer.alloc(32, 7).toString('base64');
const proofInput = ['NEXUS-SIGN/RECOVERY-PROOF/v2', sessionId, nonce, nexusId, sha256hex(newSigning.spki)].join('\n');
const proofSignature = sign('sha256', Buffer.from(proofInput, 'utf8'), { key: recovery.privateKey, dsaEncoding: 'der' });

const vectors = {
  description: 'NEXUS-SIGN recovery protocol 2 (docs/protocol/recovery-protocol-v2.md). Generated by generate-recovery-vectors.mjs.',
  phrase,
  salt_b64: salt.toString('base64'),
  iterations,
  nexus_id: nexusId,
  credential_id: credentialId,
  seed_hex: seed.toString('hex'),
  wrap_key_hex: wrapKey.toString('hex'),
  recovery_private_scalar_hex: recoveryScalar,
  recovery_public_key_pem: recovery.pem,
  recovery_spki_sha256: sha256hex(recovery.spki),
  wrap_iv_hex: iv.toString('hex'),
  wrap_aad_utf8: aad.toString('utf8'),
  wrapped_recovery_key_b64: wrapped.toString('base64'),
  setup_signing_input_utf8: setupInput,
  proof: {
    session_id: sessionId,
    nonce_b64: nonce,
    new_signing_public_key_pem: newSigning.pem,
    signing_input_utf8: proofInput,
    signature_der_b64: proofSignature.toString('base64'),
  },
  invalid: [
    { name: 'wrong phrase (last word)', phrase: [...phrase.slice(0, 11), 'abandon'] },
    { name: 'other identity in the associated data', nexus_id: '987654321' },
  ],
};

writeVectors('recovery-v2.json', `${JSON.stringify(vectors, null, 2)}\n`);
