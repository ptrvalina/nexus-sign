// Generates call-code-v1.json: the call code that the phone and the operator
// console show during a verification call (finding A2-11). Both compute it
// from the DTLS certificate fingerprints in the offer (phone) and the answer
// (operator), so a party that substitutes a fingerprint in the signalling
// (a compromised Auth Core or Redis) makes the two codes differ. The operator
// reads the code out; the customer compares it with the app.
//
//   fingerprint(sdp) = the first "a=fingerprint:<hash> <hex>" line,
//                      as "<hash in lower case> <hex in upper case>"
//   digest = SHA-256("NEXUS-SIGN/CALL-CODE/v1" || 0x00 || fingerprint(offer) || 0x00 || fingerprint(answer))
//   code   = (first 4 bytes of digest, big-endian, unsigned) mod 1 000 000, six digits
//
// Usage: node test-vectors/generate-call-code-vectors.mjs
import { createHash } from 'node:crypto';
import { writeVectors } from './vector-files.mjs';

const hex = (seed, n) => createHash('sha512').update(seed).digest('hex').slice(0, n * 2).toUpperCase().match(/../g).join(':');
const sdp = (fingerprintLine) => ['v=0', 'o=- 4611731400430051336 2 IN IP4 127.0.0.1', 's=-', 't=0 0', 'a=group:BUNDLE 0',
  'm=audio 9 UDP/TLS/RTP/SAVPF 111', 'c=IN IP4 0.0.0.0', fingerprintLine, 'a=setup:actpass', 'a=mid:0', ''].join('\r\n');

function fingerprint(text) {
  for (const raw of text.split(/\r\n|\r|\n/)) {
    const m = /^a=fingerprint:(\S+) ([0-9A-Fa-f:]+)\s*$/i.exec(raw.trim());
    if (m) return `${m[1].toLowerCase()} ${m[2].toUpperCase()}`;
  }
  return null;
}
function code(offer, answer) {
  const digest = createHash('sha256').update(Buffer.concat([
    Buffer.from('NEXUS-SIGN/CALL-CODE/v1'), Buffer.from([0]), Buffer.from(fingerprint(offer)), Buffer.from([0]), Buffer.from(fingerprint(answer)),
  ])).digest();
  return String(digest.readUInt32BE(0) % 1_000_000).padStart(6, '0');
}

const cases = [
  { name: 'sha-256 both sides', offer: sdp(`a=fingerprint:sha-256 ${hex('device-1', 32)}`), answer: sdp(`a=fingerprint:sha-256 ${hex('operator-1', 32)}`) },
  { name: 'lower-case hex and upper-case hash name are normalised', offer: sdp(`a=fingerprint:SHA-256 ${hex('device-1', 32).toLowerCase()}`), answer: sdp(`a=fingerprint:sha-256 ${hex('operator-1', 32)}`) },
  { name: 'sha-384 answer, LF line ends', offer: sdp(`a=fingerprint:sha-256 ${hex('device-2', 32)}`).replace(/\r\n/g, '\n'), answer: sdp(`a=fingerprint:sha-384 ${hex('operator-2', 48)}`) },
  { name: 'another operator certificate gives another code', offer: sdp(`a=fingerprint:sha-256 ${hex('device-1', 32)}`), answer: sdp(`a=fingerprint:sha-256 ${hex('attacker', 32)}`) },
];
const vectors = {
  description: 'Call code v1 vectors (finding A2-11). Generated by generate-call-code-vectors.mjs - do not edit by hand.',
  domain: 'NEXUS-SIGN/CALL-CODE/v1',
  valid: cases.map((c) => ({ ...c, offerFingerprint: fingerprint(c.offer), answerFingerprint: fingerprint(c.answer), code: code(c.offer, c.answer) })),
  noFingerprint: [{ name: 'offer without fingerprint', offer: 'v=0\r\nm=audio 9 UDP/TLS/RTP/SAVPF 111\r\n', answer: sdp(`a=fingerprint:sha-256 ${hex('operator-1', 32)}`) }],
};
writeVectors('call-code-v1.json', `${JSON.stringify(vectors, null, 2)}\n`);
